import logging
import os
import sys
import urllib.request
import zipfile
from xml.etree import ElementTree
from xml.etree.ElementTree import Element

OUTPUT_PATHS = ["THIRD-PARTY-NOTICES.TXT", "target/THIRD-PARTY-NOTICES.TXT"]
MAVEN_REPO = os.path.join(os.path.expanduser("~"), ".m2", "repository")
POM_FILE_NAME = "pom.xml"
NAMESPACE = "{http://maven.apache.org/POM/4.0.0}"
MAX_LICENSE_TEXT = 20000

OUTPUT_HEADER = """THIRD-PARTY NOTICES
===================

This file is generated by notices_generate.py from the local Maven repository.
Only dependencies that declare a license in their POM are included.
The license text is copied from the dependency's license file or JAR, or
fetched from the declared license URL. No links are added by the generator;
the copied license text may contain its own URLs.

"""

# DependencyLocation = tuple[str, str, str]  # (groupId, artifactId, version)
property_map: dict[str, str] = dict()
license_text_cache: dict[str, str] = dict()


def get_dependencies_from_local_pom(pom_path: str) -> list[tuple[str, str, str]]:
    """
    解析该项目的 pom.xml 文件，返回其依赖列表。
    """
    try:
        property_map.clear()
        tree = ElementTree.parse(pom_path)
        root = tree.getroot()
        parse_version(root.find(NAMESPACE + "properties"))

        dependencies_list: list[tuple[str, str, str]] = []
        for container in root.findall(NAMESPACE + "dependencies"):
            deps = container.findall(NAMESPACE + "dependency")
            dependencies_list.extend(parse_dependencies(deps))
        return dependencies_list
    except Exception as e:
        print(f"[Parse Error]: {e}", file=sys.stderr)
        raise Exception(f"[Parse Error]: {e}")


def parse_dependencies(dependencies: list[Element]) -> list[tuple[str, str, str]]:
    """
    解析一串依赖（dependencies 标签）。
    """
    unique: set[tuple[str, str, str]] = set()
    for dependency in dependencies:
        parsed = parse_dependency(dependency)
        if parsed and parsed[0] and parsed[1] and parsed[2]:
            unique.add(parsed)
    return sorted(unique)


def parse_dependency(dependency: Element) -> tuple[str, str, str]:
    """
    解析单个依赖。
    """
    group_id = dependency.find(NAMESPACE + "groupId")
    artifact_id = dependency.find(NAMESPACE + "artifactId")
    version = dependency.find(NAMESPACE + "version")
    scope = dependency.find(NAMESPACE + "scope")
    optional = dependency.find(NAMESPACE + "optional")

    if group_id is None:
        group_id = Element("groupId")
    if artifact_id is None:
        artifact_id = Element("artifactId")
    if version is None:
        version = Element("version")

    if version.text and version.text.startswith("${"):
        index = version.text[2:-1]
        version.text = property_map.get(NAMESPACE + index, version.text)

    if scope is not None and scope.text in ("test", "provided"):
        return "", "", ""
    if optional is not None and optional.text == "true":
        return "", "", ""

    return (group_id.text or "", artifact_id.text or "", version.text or "")


def parse_version(properties: Element | None) -> None:
    """
    解析 <version>${junit.version}</version> 这类属性。
    """
    global property_map
    if properties is None:
        return
    for prop in properties:
        property_map[prop.tag] = prop.text or ""


def find_pom(version_directory: str) -> str | None:
    """返回版本目录里的 .pom 文件。"""
    if not os.path.isdir(version_directory):
        return None
    for filename in sorted(os.listdir(version_directory)):
        if filename.endswith(".pom"):
            return os.path.join(version_directory, filename)
    return None


def read_pom_licenses(pom_path: str) -> list[tuple[str, str]]:
    """从 POM 的 <licenses> 节点读取许可证名称/URL。"""
    try:
        root = ElementTree.parse(pom_path).getroot()
    except Exception:
        return []
    container = root.find(NAMESPACE + "licenses")
    if container is None:
        return []
    result: list[tuple[str, str]] = []
    for license_element in container.findall(NAMESPACE + "license"):
        name = (license_element.findtext(NAMESPACE + "name") or "").strip()
        url = (license_element.findtext(NAMESPACE + "url") or "").strip()
        if name or url:
            result.append((name, url))
    return result


def read_license_files(version_directory: str) -> list[tuple[str, str]]:
    """读取依赖目录里的 LICENSE/COPYING/NOTICE 文件。"""
    result: list[tuple[str, str]] = []
    if not os.path.isdir(version_directory):
        return result
    for filename in sorted(os.listdir(version_directory)):
        lower = filename.lower()
        if not (lower.startswith("license") or lower.startswith("copying") or lower.startswith("notice")):
            continue
        try:
            with open(os.path.join(version_directory, filename), "r", encoding="utf-8", errors="replace") as file:
                result.append((filename, file.read(MAX_LICENSE_TEXT)))
        except OSError as error:
            logging.warning("[Warn] Can't read %s: %s", filename, error)
    return result


def read_jar_license_files(version_directory: str) -> list[tuple[str, str]]:
    """读取依赖 JAR 内的 LICENSE/NOTICE 原文。"""
    result: list[tuple[str, str]] = []
    if not os.path.isdir(version_directory):
        return result
    for filename in sorted(os.listdir(version_directory)):
        if not filename.endswith(".jar"):
            continue
        jar_path = os.path.join(version_directory, filename)
        try:
            with zipfile.ZipFile(jar_path) as archive:
                for entry in archive.namelist():
                    lower = entry.lower()
                    if lower.endswith(".class") or not ("license" in lower or "notice" in lower):
                        continue
                    try:
                        text = archive.read(entry).decode("utf-8", errors="replace")
                    except (KeyError, OSError):
                        continue
                    result.append((f"{filename}:{entry}", text[:MAX_LICENSE_TEXT]))
        except (zipfile.BadZipFile, OSError) as error:
            logging.warning("[Warn] Can't read %s: %s", jar_path, error)
    return result


def fetch_license_text(url: str) -> list[tuple[str, str]]:
    """按 POM 声明的 URL 抓取许可证原文（输出中不保留 URL）。"""
    if not url or not url.startswith(("http://", "https://")):
        return []
    if url in license_text_cache:
        return [("license", license_text_cache[url])]
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            data = response.read(MAX_LICENSE_TEXT * 4)
        text = data.decode("utf-8", errors="replace")[:MAX_LICENSE_TEXT]
    except Exception as error:
        logging.warning("[Warn] Can't fetch license text for %s: %s", url, error)
        return []
    if not text.strip():
        return []
    license_text_cache[url] = text
    return [("license", text)]


def read_license_texts(version_directory: str, url: str) -> list[tuple[str, str]]:
    """优先读取本地许可证原文，其次读取 JAR，最后才抓取 URL。"""
    local = read_license_files(version_directory)
    if local:
        return local
    from_jar = read_jar_license_files(version_directory)
    if from_jar:
        return from_jar
    return fetch_license_text(url)


def load_general_maven_dependencies(deps: list[tuple[str, str, str]]) -> list[tuple[str, str, str]]:
    """
    解析依赖的依赖（BFS）。
    """
    result: list[tuple[str, str, str]] = []
    visited: set[tuple[str, str, str]] = set()
    queue: list[tuple[str, str, str]] = list(deps)

    while queue:
        dependency = queue.pop()
        group_id, artifact_id, version = dependency
        if dependency in visited:
            continue
        visited.add(dependency)
        result.append(dependency)

        if not group_id or not artifact_id or not version or version in ("RELEASE", "LATEST"):
            continue

        version_directory = os.path.join(
            MAVEN_REPO, group_id.replace(".", "/"), artifact_id, version)
        if not os.path.isdir(version_directory):
            logging.warning("[Warn] Not in local repository: %s", version_directory)
            continue

        pom_path = find_pom(version_directory)
        if pom_path is None:
            logging.warning("[Warn] No POM in %s", version_directory)
            continue
        try:
            subdeps = get_dependencies_from_local_pom(pom_path)
        except Exception as error:
            logging.warning("[Warn] Can't parse %s: %s", pom_path, error)
            continue
        for subdep in subdeps:
            if subdep and subdep[2] and subdep not in visited:
                queue.append(subdep)
    return result


def initialize_outputs() -> None:
    """创建/清空输出文件，保证即使没有依赖也会生成文件。"""
    for output in OUTPUT_PATHS:
        parent = os.path.dirname(output)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with open(output, "w", encoding="utf-8") as file:
            file.write(OUTPUT_HEADER)


def build_section(dependency: tuple[str, str, str]) -> str | None:
    """生成单个依赖的 notices 段落；POM 未声明许可证时返回 None。"""
    group_id, artifact_id, version = dependency
    version_directory = os.path.join(
        MAVEN_REPO, group_id.replace(".", "/"), artifact_id, version)

    licenses = read_pom_licenses(find_pom(version_directory) or "")
    if not licenses:
        return None

    lines = [f"=== {group_id}:{artifact_id}:{version} ===", ""]
    for name, url in licenses:
        lines.append(f"License: {name or '(unnamed)'}")
        texts = read_license_texts(version_directory, url)
        if texts:
            for filename, text in texts:
                lines.append("")
                lines.append(f"--- {filename} ---")
                lines.append(text.rstrip())
        else:
            lines.append("")
            lines.append("(license text not available)")
    lines.append("")
    return "\n".join(lines) + "\n"


def fetch_licenses(saves: list[str], deps: list[tuple[str, str, str]]) -> tuple[int, int]:
    """写入每个输出文件，返回 (写入依赖数, 忽略依赖数)。"""
    written: set[tuple[str, str, str]] = set()
    included = 0
    skipped = 0
    for dependency in deps:
        if dependency in written:
            continue
        written.add(dependency)
        section = build_section(dependency)
        if section is None:
            skipped += 1
            continue
        included += 1
        for output in saves:
            with open(output, "a", encoding="utf-8") as file:
                file.write(section)
    return included, skipped


def main() -> None:
    initialize_outputs()
    direct = get_dependencies_from_local_pom(POM_FILE_NAME)
    all_dependencies = load_general_maven_dependencies(direct)
    included, skipped = fetch_licenses(OUTPUT_PATHS, all_dependencies)
    print(f"[INFO] wrote {included} dependencies (ignored {skipped} without POM license) to: "
          f"{', '.join(OUTPUT_PATHS)}")


if __name__ == "__main__":
    logging.basicConfig(level=logging.WARNING, format="%(message)s")
    main()
